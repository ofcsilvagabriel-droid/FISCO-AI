CREATE TABLE IF NOT EXISTS public.fiscoai_dados_fiscais_versoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  tipo text NOT NULL,
  dados jsonb NOT NULL,
  versao bigint NOT NULL,
  atualizado_em timestamptz NOT NULL,
  arquivado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS fiscoai_dados_fiscais_versoes_usuario_idx
  ON public.fiscoai_dados_fiscais_versoes (user_id, tipo, arquivado_em DESC);

ALTER TABLE public.fiscoai_dados_fiscais_versoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fiscoai_dados_fiscais_versoes FORCE ROW LEVEL SECURITY;
REVOKE ALL ON public.fiscoai_dados_fiscais_versoes FROM anon;
GRANT SELECT ON public.fiscoai_dados_fiscais_versoes TO authenticated;

DROP POLICY IF EXISTS "Usuario le suas versoes fiscais" ON public.fiscoai_dados_fiscais_versoes;
CREATE POLICY "Usuario le suas versoes fiscais"
ON public.fiscoai_dados_fiscais_versoes FOR SELECT TO authenticated
USING ((SELECT auth.uid()) = user_id);

CREATE OR REPLACE FUNCTION public.fiscoai_arquivar_dados_fiscais()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF OLD.dados IS DISTINCT FROM NEW.dados OR OLD.versao IS DISTINCT FROM NEW.versao THEN
    INSERT INTO public.fiscoai_dados_fiscais_versoes
      (user_id, tipo, dados, versao, atualizado_em)
    VALUES
      (OLD.user_id, OLD.tipo, OLD.dados, OLD.versao, OLD.atualizado_em);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS fiscoai_dados_fiscais_arquivar ON public.fiscoai_dados_fiscais;
CREATE TRIGGER fiscoai_dados_fiscais_arquivar
BEFORE UPDATE ON public.fiscoai_dados_fiscais
FOR EACH ROW EXECUTE FUNCTION public.fiscoai_arquivar_dados_fiscais();
